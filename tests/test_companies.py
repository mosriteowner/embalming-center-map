def _snap():
    s = Snapshot()
    for pref, co, n in REAL:
        s.facilities.setdefault(pref, []).extend(f"{co}｜施設{i}" for i in range(n))
    return s


def test_split_company():
    assert split_company(AC) == ("アルファクラブグループ", "アルファクラブ株式会社")
    assert split_company("ＳＯＵセレモニー 株式会社") == (None, "ＳＯＵセレモニー株式会社")
    assert split_company("ライフアンドデザイン・グループ株式会社") == (None, "ライフアンドデザイン・グループ株式会社")
    assert split_company("株式会社メモリードグループ") == (None, "株式会社メモリードグループ")
    # 「…グループ 株式会社」のように、後ろが法人格だけなら、グループとは見なさない
    assert split_company("ライフアンドデザイン・グループ 株式会社") == (None, "ライフアンドデザイン・グループ株式会社")


def test_real_totals_match_ifsa_declared_numbers():
    entries = company_stats(_snap())
    assert sum(e["total"] for e in entries) == 94
    assert count_companies(entries) == 36          # IFSAの「事業会社36社」と一致


def test_top_entries():
    top = {e["name"]: e for e in company_stats(_snap())}
    assert top["アルファクラブグループ"]["total"] == 23
    assert len(top["アルファクラブグループ"]["members"]) == 4
    assert top["アルファクラブグループ"]["prefs"]["埼玉県"] == 8
    assert top["株式会社ブッシュ"]["total"] == 15
    assert top["株式会社ジェイイーシー"]["total"] == 11
    assert top["燦ホールディングスグループ"]["total"] == 4          # 公益社3(東京・京都・大阪)+タルイ1
    assert top["ＳＯＵセレモニー株式会社"]["total"] == 3              # 表記の空白違いを同一視
    assert [e["name"] for e in company_stats(_snap())][:3] == [
        "アルファクラブグループ", "株式会社ブッシュ", "株式会社ジェイイーシー"]
